import assert from 'assert';
import { E6_DEFAULT_BETA, constrainE6Beta, e6BetaInChamber, e6BetaInterval, e6DisplayBeta, e6AtCrossingWall, e6CrossedPeriod, betaToLevels } from './e6-parameters.js';
import { e6CoreAreas } from './e6-areas.js';
import { createParametersPanel } from './parameters-panel.js';
const adjacent = 'side-zero-second';
const wall = constrainE6Beta(E6_DEFAULT_BETA, 0, 3);
assert(e6AtCrossingWall(wall));
const pinned = JSON.stringify(wall);
const before = e6DisplayBeta(wall);
const after = e6DisplayBeta(wall, adjacent);
assert(e6BetaInChamber(before)); assert(e6BetaInChamber(after, adjacent));
assert.strictEqual(JSON.stringify(wall), pinned);
assert(e6CrossedPeriod(before)>0 && e6CrossedPeriod(after)<0);
const oldForms = e6CoreAreas(before).periods;
const periods = e6CoreAreas(after, adjacent).periods;
assert(periods.every(v=>v>0));
assert(Math.abs(periods[1]-oldForms[1])<1e-6);
const target = [[46/30,.5],[1.5,61/60],[44/30,46/30]];
const targetPeriods = e6CoreAreas(target,adjacent).periods;
assert(Math.abs(targetPeriods[0]-1/30)<1e-12);
assert(Math.abs(targetPeriods[1]-29/60)<1e-12);
let beta=constrainE6Beta(wall,0,1.56,adjacent);
assert(e6BetaInChamber(beta,adjacent)); assert(!e6AtCrossingWall(beta));
beta=constrainE6Beta(beta,0,0,adjacent);
assert(e6AtCrossingWall(beta));
assert(e6BetaInChamber(e6DisplayBeta(beta)));
assert(e6BetaInChamber(constrainE6Beta(beta,0,1.5)));
assert.throws(()=>e6BetaInterval(beta,0,'unknown'),RangeError);
const elements=[];
function element(tag) {
 const result={tag,children:[],handlers:{},style:{setProperty(k,v){this[k]=v;}},appendChild(c){this.children.push(c);},addEventListener(k,f){this.handlers[k]=f;}};
 elements.push(result); return result;
}
globalThis.document={createElement:element};
let chamber='default', crosses=0, panel;
panel=createParametersPanel(element('div'),{getChamberId:()=>chamber,wallActions:{getOptions:b=>[{id:adjacent,atWall:e6AtCrossingWall(b),canCross:true}],onCross(){crosses++;chamber=chamber==='default'?adjacent:'default';panel.refresh();}}});
const input=elements.find(e=>e.id==='ek-beta-0');
assert(!elements.some(e=>e.textContent==='Cross Wall'));
input.value='3';input.handlers.input();
const button=elements.filter(e=>e.textContent==='Cross Wall').pop();assert(button);
const saved=panel.getBeta(); button.handlers.click();
assert.strictEqual(chamber,adjacent);assert.deepStrictEqual(panel.getBeta(),saved);
button.handlers.click();assert.strictEqual(crosses,1);
input.value='1.56';input.handlers.input();assert(e6BetaInChamber(panel.getBeta(),adjacent));
input.value='0';input.handlers.input();
const back=elements.filter(e=>e.textContent==='Cross Wall').pop();back.handlers.click();
assert.strictEqual(chamber,'default');assert.strictEqual(crosses,2);
console.log('Live chamber UI: supported boundary, pinned crossing, effective areas, target clamps, reverse crossing and stale buttons pass.');
